@pytest.mark.parametrize("method", ["REML", "ML"])
@pytest.mark.parametrize("inference", ["z", "t"])
@pytest.mark.parametrize("moderators", [[], ["yc"]])
def test_konstantopoulos_three_level_matches_metafor(method, inference, moderators):
    data = konst()
    before = data.copy(deep=True)
    reference = ORACLES[f"konst_{'yc' if moderators else 'int'}_{method}_{inference}"]
    profile = reference["profile"] is not None
    fit = oe.meta_multilevel(data=data, study="district", yi="yi", vi="vi", moderators=moderators,
                             method=method, inference=inference, profile=profile)
    pd.testing.assert_frame_equal(data, before)
    components = fit["variance_components"]
    close(components.sigma2, reference["sigma2"], rtol=2e-6)
    coefficients = fit["coefficients"]
    close(coefficients.estimate, vec(reference["beta"]), rtol=1e-6, atol=1e-9)
    close(fit["covariance"], mat(reference["vb"]), rtol=2e-6)
    close(coefficients.std_error, vec(reference["se"]), rtol=1e-6)
    close(coefficients.statistic, vec(reference["zval"]), rtol=2e-6, atol=1e-8)
    close(coefficients.p_value, vec(reference["pval"]), rtol=2e-6, atol=1e-10)
    close(coefficients.ci_low, vec(reference["ci_lb"]), rtol=1e-6, atol=1e-9)
    close(coefficients.ci_high, vec(reference["ci_ub"]), rtol=1e-6, atol=1e-9)
    if inference == "t":
        assert list(coefficients.df) == list(vec(reference["ddf"]).astype(int))
    stats_ = fit["fit"].iloc[0]
    close([stats_.loglik, stats_.aic, stats_.bic, stats_.aicc],
          [reference["fitstats"][name] for name in ("logLik", "AIC", "BIC", "AICc")], rtol=0, atol=2e-9)
    tests = fit["tests"].set_index("test")
    assert tests.loc["QE residual heterogeneity (sampling covariance only)", "statistic"] == pytest.approx(reference["QE"], rel=1e-10)
    if moderators:
        assert tests.loc["QM joint moderators", "statistic"] == pytest.approx(reference["QM"], rel=5e-6)
        assert tests.loc["QM joint moderators", "p_value"] == pytest.approx(reference["QMp"], rel=5e-6)
    close(fit["component_covariance"].to_numpy(dtype=float), mat(reference["vvc"]), rtol=2e-5)
    close(components.std_error, np.sqrt(np.diag(mat(reference["vvc"]))), rtol=1e-5)
    heterogeneity = fit["heterogeneity"].iloc[0]
    close([heterogeneity.I2_study_percent, heterogeneity.I2_effect_percent],
          reference["i2"]["components"], rtol=5e-6)
    assert heterogeneity.typical_sampling_variance == pytest.approx(reference["i2"]["typical"], rel=1e-10)
    for row, lrt in zip(components.itertuples(), reference["lrt"]):
        assert row.lrt_statistic == pytest.approx(lrt["LRT"], rel=2e-6, abs=2e-8)
        assert row.lrt_p_value == pytest.approx(lrt["pval"], rel=1e-5, abs=1e-12)
        assert row.lrt_p_value_boundary_mixture == pytest.approx(lrt["pval"]/2, rel=1e-5, abs=1e-12)
    if profile:
        close(components[["profile_ci_low", "profile_ci_high"]].to_numpy(dtype=float), mat(reference["profile"])[:, 1:], rtol=2e-6)
    new = pd.DataFrame({"yc": [-5., 0., 10.]}) if moderators else None
    prediction = oe.meta_multilevel_predict(fit, data=new)
    for name, key in (("estimate", "pred"), ("std_error", "se"), ("ci_low", "ci_lb"), ("ci_high", "ci_ub"),
                      ("pi_low", "pi_lb"), ("pi_high", "pi_ub")):
        close(prediction[name], vec(reference["predict"][key]), rtol=2e-6, atol=1e-9)
    json_safe(fit)
    assert fit.attrs["variance_solver"]["boundary"] == [False, False]


def dense_reference(data, s, x, method):
    """Independent dense NumPy/SciPy three-level likelihood maximized on log variances."""
    y = data.yi.to_numpy(float)
    studies = data.study.to_numpy()
    z = (studies[:, None] == studies[None, :]).astype(float)
    n, p = x.shape
    log_xx = np.linalg.slogdet(x.T@x)[1]

    def loglik(theta):
        v = s+theta[0]*z+theta[1]*np.eye(n)
        factor = linalg.cho_factor(v, lower=True)
        wx = linalg.cho_solve(factor, x)
        gram = x.T@wx
        beta = np.linalg.solve(gram, wx.T@y)
        r = y-x@beta
        rss = r@linalg.cho_solve(factor, r)
        logdet = 2*np.log(np.diag(factor[0])).sum()
        if method == "ML":
            return -.5*(n*math.log(2*math.pi)+logdet+rss), beta, np.linalg.inv(gram)
        return -.5*((n-p)*math.log(2*math.pi)+logdet+np.linalg.slogdet(gram)[1]-log_xx+rss), beta, np.linalg.inv(gram)

    best = optimize.minimize(lambda w: -loglik(np.exp(w))[0], np.log([.05, .03]), method="Nelder-Mead",
                             options={"xatol": 1e-12, "fatol": 1e-15, "maxiter": 20000, "maxfev": 40000})
    polished = optimize.minimize(lambda w: -loglik(np.exp(w))[0], best.x, method="BFGS", options={"gtol": 1e-11})
    theta = np.exp(polished.x)
    value, beta, covariance = loglik(theta)
    return theta, value, beta, covariance


@pytest.mark.parametrize("method", ["REML", "ML"])
def test_correlated_within_study_covariance_matches_metafor_and_dense_oracle(method):
    data, covariance = che()
    reference = ORACLES[f"che_{method}"]
    fit = oe.meta_multilevel(data=data, study="study", effect="effect", yi="yi", covariance=covariance,
                             moderators=["x1", "x2"], method=method)
    components = fit["variance_components"]
    close(components.sigma2, reference["sigma2"], rtol=2e-6)
    close(fit["coefficients"].estimate, vec(reference["beta"]), rtol=1e-6, atol=1e-9)
    close(fit["covariance"], mat(reference["vb"]), rtol=2e-6)
    close(fit["component_covariance"].to_numpy(dtype=float), mat(reference["vvc"]), rtol=2e-5)
    close(components[["profile_ci_low", "profile_ci_high"]].to_numpy(dtype=float), mat(reference["profile"])[:, 1:], rtol=2e-6)
    assert fit["fit"].iloc[0].loglik == pytest.approx(reference["fitstats"]["logLik"], abs=1e-9)
    assert fit["tests"].iloc[0].statistic == pytest.approx(reference["QE"], rel=1e-10)
    close([fit["heterogeneity"].iloc[0].I2_total_percent], [reference["i2"]["total"]], rtol=5e-6)
    x = np.column_stack([np.ones(len(data)), data.x1, data.x2])
    theta, value, beta, bread = dense_reference(data, covariance.loc[data.effect, data.effect].to_numpy(), x, method)
    close(components.sigma2, theta, rtol=1e-7)
    assert fit["fit"].iloc[0].loglik == pytest.approx(value, abs=1e-10)
    close(fit["coefficients"].estimate, beta, rtol=1e-8, atol=1e-11)
    close(fit["covariance"], bread, rtol=1e-7)
    prediction = oe.meta_multilevel_predict(fit, data=pd.DataFrame({"x1": [0., 1.], "x2": [0., -.5]}))
    close(prediction.pi_low, vec(reference["predict"]["pi_lb"]), rtol=2e-6)
    close(prediction.pi_high, vec(reference["predict"]["pi_ub"]), rtol=2e-6)
    robust = oe.meta_cr2(fit, contrasts=pd.DataFrame({"Intercept": [0., 1.], "x1": [1., 0.], "x2": [1., 0.]}, index=["sum", "mean"]),
                         null=[.1, .2])
    expected = reference["cr2"]
    close(robust["covariance"], mat(expected["vcov"]), rtol=2e-5)
    close(robust["coefficients"].df, vec(expected["df"]), rtol=2e-5)
    close(robust["coefficients"].p_value, vec(expected["p"]), rtol=5e-5)
    tests = robust["tests"].set_index("test")
    for label, key in (("joint moderators", "moderators"), ("contrasts", "contrasts")):
        assert tests.loc[label, "F_statistic"] == pytest.approx(expected[key]["F"], rel=5e-5)
        assert tests.loc[label, "df2"] == pytest.approx(expected[key]["df2"], rel=5e-5)
        assert tests.loc[label, "p_value"] == pytest.approx(expected[key]["p"], rel=5e-5)
    close(robust["contrasts"].df, [row["df2"] for row in expected["contrast_rows"]], rtol=5e-5)
    close(robust["contrasts"].statistic**2, [row["F"] for row in expected["contrast_rows"]], rtol=5e-5)
    json_safe(robust)
    assert "CR2" in str(robust) and len(robust.to_latex()) > 500


@pytest.mark.parametrize("method", ["REML", "ML"])
def test_zero_between_study_component_is_an_exact_kkt_boundary(method):
    data = pd.read_csv(FIXTURE / "boundary.csv")
    reference = ORACLES[f"boundary_{method}"]
    fit = oe.meta_multilevel(data=data, study="study", effect="effect", yi="yi", vi="vi", method=method)
    components = fit["variance_components"]
    assert components.sigma2.iloc[0] == 0 and bool(components.boundary.iloc[0])
    assert components.std_error.iloc[0] is None
    assert vec(reference["sigma2"])[0] < 1e-8  # metafor's log-scale optimizer stops near zero
    assert components.sigma2.iloc[1] == pytest.approx(vec(reference["sigma2"])[1], rel=2e-6)
    assert fit["coefficients"].estimate.iloc[0] == pytest.approx(reference["beta"], rel=2e-7)
    loglik = fit["fit"].iloc[0].loglik
    # metafor's log-scale optimizer stops near, not at, zero: never better than the exact boundary.
    assert reference["ll"]-1e-10 <= loglik <= reference["ll"]+1e-6
    assert components.profile_ci_low.iloc[0] == 0
    assert components.lrt_statistic.iloc[0] == pytest.approx(0, abs=1e-10)
    assert fit.attrs["variance_solver"]["boundary"] == [True, False]


def test_analytic_scores_and_observed_hessian_match_numerical_derivatives():
    data, covariance = che()
    fit = oe.meta_multilevel(data=data, study="study", effect="effect", yi="yi", covariance=covariance,
                             moderators=["x1"], profile=False)
    _, values = ml_core.load_state(fit)
    lik = values["likelihood"]
    for method in ("ML", "REML"):
        def objective(theta, method=method):
            point = lik.evaluate(theta[None])
            return point["ll_"+method][0], point["score_"+method][0], point["hessian_"+method][0]
        report = check_derivatives(objective, torch.tensor([.7, .25], dtype=torch.float64))
        assert report["gradient_max_rel_error"] < 1e-8
        assert report["hessian_max_rel_error"] < 1e-7


def test_saved_state_json_restores_tables_and_rejects_tampering(monkeypatch):
    data, covariance = che()
    fit = oe.meta_multilevel(data=data, study="study", effect="effect", yi="yi", covariance=covariance,
                             moderators=["x1", "x2"], inference="t", profile=False)
    state = json.loads(json.dumps(fit.attrs["prediction_state"], allow_nan=False, sort_keys=True))
    copied = copy.deepcopy(state)

    def forbidden(*args, **kwargs):
        raise AssertionError("restoration must not rerun the optimizer")
    monkeypatch.setattr(ml_kernels.Likelihood, "maximize", forbidden)
    restored = ml_core.make_result(state)
    for name in fit:
        pd.testing.assert_frame_equal(fit[name], restored[name])
    assert state == copied
    assert len(fit.to_latex()) > 2000 and "variance_components" in str(fit)
    pd.testing.assert_frame_equal(oe.meta_cr2(state)["covariance"], oe.meta_cr2(fit)["covariance"])
    for change in ({"sigma2": [state["sigma2"][0]*1.01, state["sigma2"][1]]},
                   {"y": [state["y"][0]+1e-3, *state["y"][1:]]}, {"method": "ML"}):
        tampered = copy.deepcopy(state)
        tampered.update(change)
        resealed = ml_core._seal(tampered)
        with pytest.raises(AnalysisError) as error:
            ml_core.load_state(resealed)
        assert error.value.code == "invalid_result_state"
    with pytest.raises(AnalysisError) as error:
        ml_core.load_state({**state, "checksum": "0"*64})
    assert error.value.code == "invalid_result_state"


def multilevel_error(**changes):
    data, covariance = che()
    arguments = dict(data=data, study="study", effect="effect", yi="yi", vi="vi", moderators=["x1"])
    arguments.update(changes)
    with pytest.raises(AnalysisError) as error:
        oe.meta_multilevel(**arguments)
    return error.value.code


def test_three_level_failure_contract():
    data, covariance = che()
    missing = data.copy()
    missing.loc[3, "yi"] = np.nan
    assert multilevel_error(data=missing) == "missing_values"
    assert multilevel_error(covariance=covariance) == "invalid_spec"
    assert multilevel_error(vi=None) == "invalid_spec"
    assert multilevel_error(method="DL") == "invalid_spec"
    assert multilevel_error(inference="hksj") == "invalid_spec"
    assert multilevel_error(device="mps") == "unsupported_device"
    assert multilevel_error(weights="vi") == "unsupported_weights"
    assert multilevel_error(moderators=["x1", "x1"]) == "invalid_spec"
    flagged = data.assign(flag=data.x1 > 0)
    assert multilevel_error(data=flagged, moderators=["flag"]) == "non_numeric_column"
    single = data.drop_duplicates("study").reset_index(drop=True)
    assert multilevel_error(data=single) == "unidentified_components"
    cross = covariance.copy()
    cross.iloc[0, 5] = cross.iloc[5, 0] = 1e-6
    assert multilevel_error(vi=None, covariance=cross) == "unsupported_dependence"
    asymmetric = covariance.copy()
    asymmetric.iloc[1, 2] = np.nextafter(asymmetric.iloc[1, 2], 1)
    assert multilevel_error(vi=None, covariance=asymmetric) == "invalid_covariance"
    indefinite = covariance.copy()
    indefinite.iloc[1, 2] = indefinite.iloc[2, 1] = 5.0
    assert multilevel_error(vi=None, covariance=indefinite) == "invalid_covariance"
    shuffled = covariance.rename(index={"e00": "zz"})
    assert multilevel_error(vi=None, covariance=shuffled) == "covariance_alignment"
    zero = data.assign(vi=0.0)
    assert multilevel_error(data=zero) == "invalid_covariance"
    constant = data.assign(c=1.0)
    assert multilevel_error(data=constant, moderators=["c"]) == "singular_design"
    big = pd.concat([data]*60, ignore_index=True)
    big["effect"] = range(len(big))
    assert multilevel_error(data=big) == "resource_limit"
    with pytest.raises(AnalysisError) as error:
        oe.meta_multilevel_predict(oe.meta_multilevel(data=data, study="study", yi="yi", vi="vi", profile=False),
                                   data=pd.DataFrame({"x1": [1.]}))
    assert error.value.code == "invalid_spec"


def test_aligned_covariance_ignores_axis_order_and_preserves_inputs():
    data, covariance = che()
    order = list(reversed(covariance.index))
    shuffled = covariance.loc[order, order]
    before = shuffled.copy(deep=True)
    left = oe.meta_multilevel(data=data, study="study", effect="effect", yi="yi", covariance=covariance, profile=False)
    right = oe.meta_multilevel(data=data, study="study", effect="effect", yi="yi", covariance=shuffled, profile=False)
    pd.testing.assert_frame_equal(left["coefficients"], right["coefficients"])
    pd.testing.assert_frame_equal(shuffled, before)
    diagonal = oe.meta_multilevel(data=data, study="study", effect="effect", yi="yi",
                                  covariance=pd.DataFrame(np.diag(data.vi), index=data.effect, columns=data.effect), profile=False)
    vi = oe.meta_multilevel(data=data, study="study", effect="effect", yi="yi", vi="vi", profile=False)
    close(diagonal["variance_components"].sigma2, vi["variance_components"].sigma2, rtol=1e-12)


