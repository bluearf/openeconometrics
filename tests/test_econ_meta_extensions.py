def asymmetric():
    return pd.read_csv(FIXTURE / "asymmetric.csv")


@pytest.mark.parametrize("method", ["REML", "ML", "DL", "common"])
@pytest.mark.parametrize("case", ["hack_L0", "hack_R0", "hack_right", "asym_L0", "asym_R0"])
def test_trimfill_matches_metafor(method, case):
    name, variant = case.split("_")
    data = hackshaw() if name == "hack" else asymmetric()
    before = data.copy(deep=True)
    reference = ORACLES[f"trimfill_{name}_{method}_{variant}"]
    options = {"side": "right"} if variant == "right" else {"estimator": variant}
    result = oe.meta_trimfill(data=data, yi="yi", vi="vi", study="study", method=method, **options)
    pd.testing.assert_frame_equal(data, before)
    summary = result["summary"].iloc[0]
    assert summary.k0 == reference["k0"] and summary.side == reference["side"]
    assert summary.se_k0 == pytest.approx(reference["se_k0"], rel=1e-12)
    if variant == "R0":
        assert summary.p_k0 == pytest.approx(reference["p_k0"], rel=1e-12)
    adjusted = result["estimates"].iloc[1]
    tolerance = 1e-9 if method in ("DL", "common") else 2e-7
    assert adjusted.estimate == pytest.approx(vec(reference["beta"])[0], rel=tolerance, abs=1e-12)
