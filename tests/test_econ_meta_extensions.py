    robust = oe.meta_cr2(fit, contrasts=pd.DataFrame({"Intercept": [0., 1.], "yc": [1., 0.], "z": [1., 0.]}, index=["a", "b"]),
                         null=pd.Series([.01, .1], index=["a", "b"]))
    close(robust["covariance"], mat(reference["vcov"]), rtol=2e-6)
    coefficients = robust["coefficients"]
    close(coefficients.std_error, vec(reference["se"]), rtol=1e-6)
    close(coefficients.df, vec(reference["df"]), rtol=1e-6)
    close(coefficients.p_value, vec(reference["p"]), rtol=5e-6)
    tests = robust["tests"].set_index("test")
    for label, key in (("joint moderators", "moderators"), ("contrasts", "contrasts")):
        assert tests.loc[label, "F_statistic"] == pytest.approx(reference[key]["F"], rel=5e-6)
        assert tests.loc[label, "df2"] == pytest.approx(reference[key]["df2"], rel=5e-6)
        assert tests.loc[label, "p_value"] == pytest.approx(reference[key]["p"], rel=5e-6)
        assert tests.loc[label, "wald_statistic"] == pytest.approx(reference[key]["Q"], rel=5e-6)
    assert robust.attrs["refitted"] is False
    pd.testing.assert_frame_equal(fit["coefficients"], oe.meta_multilevel(
        data=data, study="district", yi="yi", vi="vi", moderators=["yc", "z"], profile=False)["coefficients"])


