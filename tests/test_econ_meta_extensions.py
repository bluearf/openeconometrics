# ---- step-function selection models ----------------------------------------------------


def numpy_selection_loglik(y, v, x, steps, beta, tau2, omega):
    """Independent NumPy/SciPy Vevea-Hedges log likelihood (alternative 'greater')."""
    mu = x@beta
    eta = v+tau2
    s = np.sqrt(eta)
    p = stats.norm.sf(y/np.sqrt(v))
    group = np.searchsorted(steps, p, side="left")
    edges = np.column_stack([np.full_like(y, np.inf), *[np.sqrt(v)*stats.norm.isf(a) for a in steps[:-1]],
                             np.full_like(y, -np.inf)])
    cdf = stats.norm.cdf((edges-mu[:, None])/s[:, None])
    area = (cdf[:, :-1]-cdf[:, 1:])@omega
    return float(np.sum(np.log(omega[group])+stats.norm.logpdf(y, mu, s)-np.log(area)))


@pytest.mark.parametrize("case", ["hack_4", "hack_2", "moderator"])
def test_selection_model_matches_metafor_weightr_and_numpy_likelihood(case):
    if case == "moderator":
        data, moderators, steps = pd.read_csv(FIXTURE / "selection_moderator.csv"), ["x"], [.05, .5, 1.]
        reference = ORACLES["selection_moderator"]
    else:
        data, moderators = hackshaw(), []
        steps = [.025, .10, .50, 1.] if case == "hack_4" else [.025, 1.]
        reference = ORACLES[f"selection_{case}"]
    result = oe.meta_selection(data=data, yi="yi", vi="vi", study="study", moderators=moderators, steps=steps)
    coefficients = result["coefficients"]
    # metafor's derivative-free BFGS stop point resolves parameters to ~1e-6;
    # the log likelihood here is never lower (asserted below), so the metafor
    # comparison uses that resolution and stationarity is checked independently.
    close(coefficients.estimate, vec(reference["beta"]), rtol=2e-5, atol=5e-6)
    close(coefficients.std_error, vec(reference["se"]), rtol=5e-5)
    close(result["covariance"], mat(reference["vb"]), rtol=1e-4)
    heterogeneity = result["heterogeneity"].iloc[0]
    assert heterogeneity.tau2 == pytest.approx(reference["tau2"], rel=2e-5, abs=1e-9)
    assert heterogeneity.std_error == pytest.approx(reference["se_tau2"], rel=1e-4)
    weights = result["selection_weights"]
    close(weights.estimate, vec(reference["delta"]), rtol=2e-5)
    close(weights.std_error.iloc[1:].astype(float), vec(reference["se_delta"])[1:], rtol=1e-4)
    close(weights.statistic.iloc[1:].astype(float), vec(reference["zval_delta"])[1:], rtol=1e-4)
    assert list(weights.k) == list(vec(reference["k_intervals"]).astype(int))
    fit = result["fit"].iloc[0]
    assert fit.loglik == pytest.approx(reference["ll"], abs=1e-8)
    assert fit.loglik >= reference["ll"]-1e-10
    assert fit.loglik_unadjusted == pytest.approx(reference["ll0"], abs=1e-9)
    tests = result["tests"]
    assert tests.iloc[0].statistic == pytest.approx(reference["LRT"], rel=1e-6, abs=1e-8)
    assert tests.iloc[0].df == reference["LRTdf"]
    assert tests.iloc[0].p_value == pytest.approx(reference["LRTp"], rel=1e-5)
    assert tests.iloc[1].statistic == pytest.approx(reference["LRT_tau2"], rel=1e-5, abs=1e-8)
    # weightr's L-BFGS-B has a looser default stopping rule; agreement is coarser.
    wr = reference["weightr"]
    estimates = [heterogeneity.tau2, *coefficients.estimate, *weights.estimate.iloc[1:]]
    close(estimates, vec(wr["adj_est"]), rtol=5e-3, atol=5e-4)
    # weightr's objective omits the normal constant; its stop point is never better.
    constant = .5*len(data)*math.log(2*math.pi)
    assert fit.loglik >= -wr["neg_ll_adj"]-constant-1e-10
    assert fit.loglik_unadjusted >= -wr["neg_ll_unadj"]-constant-1e-10
    y, v = data.yi.to_numpy(float), data.vi.to_numpy(float)
    x = np.column_stack([np.ones(len(y)), *[data[m].to_numpy(float) for m in moderators]])
    omega = weights.estimate.to_numpy(float)
    beta = coefficients.estimate.to_numpy(float)
    value = numpy_selection_loglik(y, v, x, np.array(steps), beta, heterogeneity.tau2, omega)
    assert fit.loglik == pytest.approx(value, abs=1e-10)
    theta = np.r_[beta, heterogeneity.tau2, omega[1:]]

    def loglik(t):
        return numpy_selection_loglik(y, v, x, np.array(steps), t[:len(beta)], t[len(beta)], np.r_[1., t[len(beta)+1:]])
    gradient = [(loglik(theta+h)-loglik(theta-h))/(2*h[i]) for i, h in enumerate(np.diag(1e-5*np.maximum(np.abs(theta), 1e-2)))]
    assert np.max(np.abs(gradient)) < 1e-6
    json_safe(result)


