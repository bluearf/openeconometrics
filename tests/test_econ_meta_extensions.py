def test_cr2_on_published_three_level_data_matches_clubsandwich():
    data = konst()
    reference = ORACLES["konst_cr2"]
    fit = oe.meta_multilevel(data=data, study="district", yi="yi", vi="vi", moderators=["yc", "z"], profile=False)
