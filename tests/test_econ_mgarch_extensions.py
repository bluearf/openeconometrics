PAIRS = {2: [(0, 0), (1, 0), (1, 1)], 3: [(0, 0), (1, 0), (1, 1), (2, 0), (2, 1), (2, 2)]}


# ---- explicit NumPy recursions (physical units) ----------------------------------------------


def _sym(values, d):
    out = np.zeros((d, d))
    for value, (i, j) in zip(values, PAIRS[d], strict=True):
        out[i, j] = out[j, i] = value
    return out


def diagonal_path(values, y, initial, kind):
    """H_t of the diagonal VECH or diagonal BEKK, from the physical parameter vector."""
    d = y.shape[1]
    p = len(PAIRS[d])
    if kind == "dvech":
        c, a, b = (_sym(values[k * p:(k + 1) * p], d) for k in range(3))
    else:
        lower = np.zeros((d, d))
        for value, (i, j) in zip(values[:p], PAIRS[d], strict=True):
            lower[i, j] = value
        av, bv = values[p:p + d], values[p + d:p + 2 * d]
        c = lower @ lower.T
        a, b = np.outer(av, av), np.outer(bv, bv)
    h = initial.copy()
    path = [h]
    for t in range(1, len(y)):
        h = c + a * np.outer(y[t - 1], y[t - 1]) + b * h
        path.append(h)
    return np.array(path)


def adcc_path(params, y, *, initial_variances, target, convention="openecon", nbar=None):
    """Asymmetric DCC by explicit loops; ``params`` = (omega, alpha, beta) per series, then
    the correlation-target parameters (only for ``openecon``), a, b, g."""
    d = y.shape[1]
    garch = np.asarray(params[:3 * d]).reshape(d, 3)
    a, b, g = params[-3:]
    h = np.empty_like(y)
    h[0] = initial_variances
    for t in range(1, len(y)):
        h[t] = garch[:, 0] + garch[:, 1] * y[t - 1] ** 2 + garch[:, 2] * h[t - 1]
    z = y / np.sqrt(h)
    n = z * (z < 0)
    if convention == "rmgarch":
        target = np.cov(z.T)
        nbar = np.cov(n.T)
        q = (1 - a - b) * target - g * nbar + a * np.ones((d, d)) + g * np.ones((d, d)) \
            + b * target
    else:
        nbar = n.T @ n / len(y) if nbar is None else nbar
        q = target.copy()
    covariances, correlations = [], []
    for t in range(len(y)):
        r = q / np.sqrt(np.outer(np.diag(q), np.diag(q)))
        correlations.append(r)
        covariances.append(np.sqrt(np.outer(h[t], h[t])) * r)
        q = (1 - a - b) * target - g * nbar + a * np.outer(z[t], z[t]) + b * q \
            + g * np.outer(n[t], n[t])
    return np.array(covariances), np.array(correlations), target, nbar


def gaussian_ll(covariances, y):
    out = []
    for covariance, residual in zip(covariances, y, strict=True):
        sign, logdet = np.linalg.slogdet(covariance)
        assert sign > 0
        out.append(-0.5 * (len(residual) * np.log(2 * np.pi) + logdet
                           + residual @ np.linalg.solve(covariance, residual)))
    return np.array(out)


def adcc_values_ll(values, y, initial):
    """Log likelihood from the physical aDCC vector of oe.mgarch_adcc (zero mean)."""
    d = y.shape[1]
    target = np.eye(d)
    k = 3 * d
    for value, (i, j) in zip(values[k:k + d * (d - 1) // 2],
                             [(i, j) for i in range(d) for j in range(i)], strict=True):
        target[i, j] = target[j, i] = value
    params = np.r_[values[:k], values[-3:]]
    path, _, _, _ = adcc_path(params, y, initial_variances=np.diag(initial), target=target)
    return gaussian_ll(path, y).sum()


def numerical_hessian(function, point):
    def central(scale):
        h = scale * (1 + np.abs(point))
        value = function(point)
        out = np.zeros((len(point), len(point)))
        for i in range(len(point)):
            di = np.eye(len(point))[i] * h[i]
            out[i, i] = (function(point + di) - 2 * value + function(point - di)) / h[i] ** 2
            for j in range(i):
                dj = np.eye(len(point))[j] * h[j]
                out[i, j] = out[j, i] = (
                    function(point + di + dj) - function(point + di - dj)
                    - function(point - di + dj) + function(point - di - dj)
                ) / (4 * h[i] * h[j])
        return out

    return (4 * central(1e-4) - central(2e-4)) / 3


def numerical_gradient(function, point, scale=1e-5):
    h = scale * (1 + np.abs(point))
    return np.array([(function(point + np.eye(len(point))[i] * h[i])
                      - function(point - np.eye(len(point))[i] * h[i])) / (2 * h[i])
                     for i in range(len(point))])


# ---- data --------------------------------------------------------------------------------------


def simulate_dvech(n=400, seed=11, d=2):
    rng = np.random.default_rng(seed)
    c = np.array([[0.1, 0.03, 0.02], [0.03, 0.08, 0.025], [0.02, 0.025, 0.09]])[:d, :d]
    a = np.array([[0.12, 0.06, 0.05], [0.06, 0.10, 0.05], [0.05, 0.05, 0.11]])[:d, :d]
    b = np.array([[0.80, 0.75, 0.72], [0.75, 0.82, 0.74], [0.72, 0.74, 0.81]])[:d, :d]
    h, e, rows = c / (1 - a - b), np.zeros(d), []
    for _ in range(n + 200):
        h = c + a * np.outer(e, e) + b * h
        e = np.linalg.cholesky(h) @ rng.normal(size=d)
        rows.append(e)
    return pd.DataFrame(np.array(rows[200:]), columns=["x", "y", "z"][:d])


# ---- rmgarch aDCC --------------------------------------------------------------------------


def _rmgarch_params():
    values = dict(zip(RMGARCH["names"], RMGARCH["params"], strict=True))
    garch = [values[f"[{s}].{p}"] for s in ("x", "y") for p in ("omega", "alpha1", "beta1")]
    return np.array(garch + [values["[Joint]dcca1"], values["[Joint]dccb1"],
                             values["[Joint]dccg1"]])


def test_adcc_recursion_reproduces_rmgarch():
    y = np.array(RMGARCH["y"])
    params = _rmgarch_params()
    path, correlation, target, nbar = adcc_path(
        params, y, initial_variances=np.mean(y ** 2, axis=0), target=None,
        convention="rmgarch")
    assert_allclose(target, RMGARCH["Qbar"], rtol=1e-12)
    assert_allclose(nbar, RMGARCH["Nbar"], rtol=1e-12)
    assert_allclose(correlation[:, 0, 1], RMGARCH["correlation_xy"], rtol=1e-10, atol=1e-12)
    assert_allclose(path[:, 0, 0], RMGARCH["variance_x"], rtol=1e-10)
    assert_allclose(path[:, 1, 1], RMGARCH["variance_y"], rtol=1e-10)
    assert_allclose(gaussian_ll(path, y), RMGARCH["log_likelihoods"], rtol=0, atol=1e-10)
    assert gaussian_ll(path, y).sum() == pytest.approx(RMGARCH["loglik"], abs=1e-8)


def _adcc_matrices(params, target, d=2, nbar=None):
    garch = torch.tensor(params[:3 * d], dtype=torch.float64).reshape(d, 3)
    m = {"mu": torch.zeros(d, dtype=torch.float64), "omega": garch[:, 0],
         "alpha": garch[:, 1], "beta": garch[:, 2],
         "target": torch.tensor(target, dtype=torch.float64),
         "dcc_alpha": torch.tensor(params[-3], dtype=torch.float64),
         "dcc_beta": torch.tensor(params[-2], dtype=torch.float64),
         "dcc_gamma": torch.tensor(params[-1], dtype=torch.float64)}
    if nbar is not None:
        m["nbar"] = torch.tensor(nbar, dtype=torch.float64)
    return m


def test_adcc_kernel_matches_the_recursion_and_reduces_to_dcc():
    y = np.array(RMGARCH["y"])
    params = _rmgarch_params()
    initial = np.diag(np.mean(y ** 2, axis=0))
    target = np.array([[1.0, 0.6], [0.6, 1.0]])
    m = _adcc_matrices(params, target)
    path, _, state = kernels.covariance_path(m, torch.tensor(y), torch.tensor(initial), "adcc")
    expected, _, _, nbar = adcc_path(params, y, initial_variances=np.diag(initial), target=target)
    assert_allclose(path.numpy(), expected, rtol=1e-12, atol=1e-14)
    assert_allclose(state["nbar"].numpy(), nbar, rtol=1e-12)
    assert float(kernels.matrix_log_likelihood(m, torch.tensor(y), torch.tensor(initial),
                                               "adcc")) == pytest.approx(
        gaussian_ll(expected, y).sum(), abs=1e-9)
    # The Nbar override (rmgarch's centred moment) is used verbatim.
    custom = _adcc_matrices(params, target, nbar=RMGARCH["Nbar"])
    path, _, _ = kernels.covariance_path(custom, torch.tensor(y), torch.tensor(initial), "adcc")
    expected, _, _, _ = adcc_path(params, y, initial_variances=np.diag(initial), target=target,
                                  nbar=np.array(RMGARCH["Nbar"]))
    assert_allclose(path.numpy(), expected, rtol=1e-12, atol=1e-14)
    # Scalar limit: g = 0 is the DCC model.
    zero = _adcc_matrices(np.r_[params[:-1], 0.0], target)
    dcc = {key: value for key, value in zero.items() if key != "dcc_gamma"}
    assert float(kernels.matrix_log_likelihood(zero, torch.tensor(y), torch.tensor(initial),
                                               "adcc")) == pytest.approx(
        float(kernels.matrix_log_likelihood(dcc, torch.tensor(y), torch.tensor(initial),
                                            "dcc")), abs=1e-10)
    # delta = largest eigenvalue of Qbar^-1/2 Nbar Qbar^-1/2.
    root = np.linalg.cholesky(target)
    inner = np.linalg.solve(root, np.linalg.solve(root, nbar).T)
    assert float(kernels.asymmetry_scale(torch.tensor(target), torch.tensor(nbar))) \
        == pytest.approx(np.linalg.eigvalsh(inner).max(), rel=1e-12)


@pytest.mark.parametrize("kind", ["dvech", "dbekk"])
def test_diagonal_models_match_the_recursion_scores_and_hessian(kind):
    y = simulate_dvech(n=40).to_numpy()
    initial = y[:20].T @ y[:20] / 20
    point = np.array([0.1, 0.03, 0.08, 0.12, 0.06, 0.1, 0.8, 0.7, 0.82]) if kind == "dvech" \
        else np.array([0.3, 0.08, 0.28, 0.35, 0.3, 0.9, 0.88])

    def function(q):
        return gaussian_ll(diagonal_path(q, y, initial, kind), y).sum()

    native = kernels.gradient(
        lambda q: kernels.matrix_log_likelihood(kernels.physical_matrices(q, kind, 2, False),
                                                torch.tensor(y), torch.tensor(initial), kind),
        torch.tensor(point), True)
    assert float(native[0]) == pytest.approx(function(point), abs=1e-10)
    assert_allclose(native[1].numpy(), numerical_gradient(function, point), rtol=2e-6,
                    atol=3e-5)
    assert_allclose(native[2].numpy(), numerical_hessian(function, point), rtol=2e-4, atol=2e-4)
    raw = kernels.encode(torch.tensor(point), kind, 2, False)
    assert_allclose(kernels.decode(raw, kind, 2, False)[0].numpy(), point, atol=1e-12)


def test_variances_are_the_univariate_garch_of_oe_arch():
    """Scalar limits: every conditional variance of the diagonal VECH, diagonal BEKK and aDCC
    models is the univariate GARCH(1,1) recursion of oe.arch's kernel (presample matched)."""
    y = simulate_dvech(n=200).to_numpy()
    d = 2
    pieces = {"dvech": (np.array([0.1, 0.03, 0.08]), np.array([0.12, 0.06, 0.1]),
                        np.array([0.8, 0.7, 0.82]))}
    for kind in ("dvech", "dbekk", "adcc"):
        if kind == "dvech":
            c, a, b = (_sym(v, d) for v in pieces["dvech"])
            values = np.concatenate(pieces["dvech"])
            omega, alpha, beta = np.diag(c), np.diag(a), np.diag(b)
        elif kind == "dbekk":
            lower = np.array([[0.3, 0.0], [0.08, 0.28]])
            av, bv = np.array([0.35, 0.3]), np.array([0.9, 0.88])
            values = np.r_[0.3, 0.08, 0.28, av, bv]
            omega, alpha, beta = np.diag(lower @ lower.T), av ** 2, bv ** 2
        else:
            omega, alpha, beta = np.array([0.1, 0.08]), np.array([0.1, 0.12]), np.array([0.8,
                                                                                        0.75])
        for i in range(d):
            layout = Layout(model="garch", dist="normal", arch_lags=(1,), garch_lags=(1,))
            like = ArchLikelihood(torch.tensor(y[:, i]), torch.empty((len(y), 0),
                                  dtype=torch.float64), torch.empty((len(y), 0),
                                  dtype=torch.float64), layout)
            theta = torch.tensor([alpha[i], beta[i], omega[i]], dtype=torch.float64)
            univariate = like.evaluate(theta, derivatives=False).variance.numpy()
            # oe.arch's first variance h_1 = omega + (alpha + beta) mean(y^2) as the start.
            initial = np.diag([omega[j] + (alpha[j] + beta[j]) * np.mean(y[:, j] ** 2)
                               for j in range(d)])
            if kind == "adcc":
                m = _adcc_matrices(np.r_[np.c_[omega, alpha, beta].ravel(), 0.03, 0.9, 0.02],
                                   np.eye(d))
                path = kernels.covariance_path(m, torch.tensor(y), torch.tensor(initial),
                                               kind)[0].numpy()
            else:
                initial[0, 1] = initial[1, 0] = 0.1 * math.sqrt(initial[0, 0] * initial[1, 1])
                path = diagonal_path(values, y, initial, kind)
            assert_allclose(path[:, i, i], univariate, rtol=1e-12)


