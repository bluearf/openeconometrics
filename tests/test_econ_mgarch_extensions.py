@pytest.mark.parametrize("kind", ["dvech", "dbekk"])
def test_diagonal_joint_fits_full_covariance_and_exact_forecasts(diagonal_fits, kind):
    data, fits = diagonal_fits
    result = fits[kind]
    y = data.to_numpy()
    initial = np.array(result.extra["initialization"]["initial_covariance"])
    point = np.array([c.estimate for c in result.coefficients])

    def function(q):
        return gaussian_ll(diagonal_path(q, y, initial, kind), y).sum()

    assert result.metrics["log_likelihood"] == pytest.approx(function(point), abs=1e-10)
    assert_allclose(numerical_gradient(function, point), 0.0, atol=2e-3)
    expected = np.linalg.inv(-numerical_hessian(function, point))
    assert_allclose(result.covariance_matrix, expected, rtol=3e-4, atol=2e-6)
    path = diagonal_path(point, y, initial, kind)
    steps, forecasts = 6, []
    m = kernels.physical_matrices(torch.tensor(point), kind, 2, False)
    if kind == "dvech":
        c, a, b = (m[name].numpy() for name in ("C", "A", "B"))
    else:
        c = (m["C"] @ m["C"].T).numpy()
        a, b = np.outer(m["a"], m["a"]), np.outer(m["b"], m["b"])
    shock, h = np.outer(y[-1], y[-1]), path[-1]
    for _ in range(steps):
        h = c + a * shock + b * h
        forecasts.append(h)
        shock = h
    restored = ResultBundle.model_validate_json(json.dumps(result.model_dump(), allow_nan=False))
    table = oe.forecast(restored, steps)
    assert_allclose(np.array(table.attrs["conditional_covariance"]), np.array(forecasts),
                    rtol=1e-12)
    assert table.attrs["exact_full_covariance_horizons"] == list(range(1, steps + 1))
    assert "tabular" in result.to_latex()
    assert result.provenance["stata_parity_validated"] is False
    constraints = result.extra["constraints"]
    if kind == "dvech":
        assert {"ding_engle_psd", "unconditional_covariance_positive_definite"} <= set(
            constraints)
        assert [c.term for c in result.coefficients][:3] == ["C:x:x", "C:y:x", "C:y:y"]
    else:
        assert constraints["spectral_radius"] < 1
        assert [c.term for c in result.coefficients][-4:] == ["A:x", "A:y", "B:x", "B:y"]


