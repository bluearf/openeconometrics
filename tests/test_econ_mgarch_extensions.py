"""Diagonal VECH, diagonal BEKK and asymmetric DCC (MARKET-161) against independent references.

* ``tests/fixtures/garch_extensions/rmgarch_adcc.json`` -- R ``rmgarch`` 1.4 ``dccfit`` of a
  simulated bivariate aDCC series (generated by scripts/generate_garch_extension_oracles.R).
  An explicit NumPy recursion with rmgarch's conventions (two-step targets
  ``Qbar = cov(z)``, ``Nbar = cov(n)``, presample ``Q_0 = Qbar`` with ``z_0 = n_0 = 1``,
  rugarch's ``h_1 = mean(e^2)``) must reproduce rmgarch's per-period likelihoods and
  correlations; the same recursion with oe.mgarch_adcc's conventions is then the oracle of
  the Torch kernel.
* Explicit NumPy recursions of every model in physical units (no production parameter
  map), numerical derivatives of them, and the univariate ``oe.arch`` GARCH kernel for the
  scalar limits.
"""

