def test_adcc_joint_fit_against_the_recursion_and_rmgarch(adcc_fit):
    y = np.array(RMGARCH["y"])
    result = adcc_fit
    initial = np.array(result.extra["initialization"]["initial_covariance"])
    point = np.array([c.estimate for c in result.coefficients])
    assert [c.term for c in result.coefficients][-3:] == ["dcc_alpha", "dcc_beta", "dcc_gamma"]

    def function(q):
        return adcc_values_ll(q, y, initial)

    assert result.metrics["log_likelihood"] == pytest.approx(function(point), abs=1e-9)
    assert_allclose(numerical_gradient(function, point), 0.0, atol=2e-3)
    expected = np.linalg.inv(-numerical_hessian(function, point))
    assert_allclose(result.covariance_matrix, expected, rtol=1e-3, atol=2e-6)
    constraints = result.extra["constraints"]
    assert 0 < constraints["adcc_persistence"] < 1
    # rmgarch estimates the same model in two steps with empirical (centred) targets and
    # its own start-up: a different estimator, so its estimates are compared loosely.
    errors = {c.term: c.std_error for c in result.coefficients}
    estimates = {c.term: c.estimate for c in result.coefficients}
    names = [f"{p}:{s}" for s in ("x", "y") for p in ("omega", "alpha", "beta")] \
        + ["dcc_alpha", "dcc_beta", "dcc_gamma"]
    for name, value in zip(names, _rmgarch_params(), strict=True):
        assert abs(estimates[name] - value) < 2 * errors[name], name
    # Forecasts: exact one step, labeled plug-in beyond.
    restored = ResultBundle.model_validate_json(json.dumps(result.model_dump(), allow_nan=False))
    table = oe.forecast(restored, 4)
    assert table.attrs["exact_full_covariance_horizons"] == [1]
    assert "approximation" in table.attrs["forecast_method"]
    target = np.array(result.extra["parameter_matrices"]["target"])
    path, _, _, nbar = adcc_path(np.r_[point[:6], point[-3:]], y,
                                 initial_variances=np.diag(initial), target=target)
    z_last = y[-1] / np.sqrt(np.diag(path[-1]))
    neg = z_last * (z_last < 0)
    a, b, g = point[-3:]
    q_last = np.array(result.extra["state"]["Q"])
    q_next = (1 - a - b) * target - g * nbar + a * np.outer(z_last, z_last) + b * q_last \
        + g * np.outer(neg, neg)
    garch = point[:6].reshape(2, 3)
    h_next = garch[:, 0] + garch[:, 1] * y[-1] ** 2 + garch[:, 2] * np.diag(path[-1])
    r_next = q_next / np.sqrt(np.outer(np.diag(q_next), np.diag(q_next)))
    assert_allclose(table.attrs["conditional_covariance"][0],
                    np.sqrt(np.outer(h_next, h_next)) * r_next, rtol=1e-10)
    assert_allclose(result.extra["state"]["nbar"], nbar, rtol=1e-10)


def test_three_dimensional_diagonal_bekk_and_guards():
    data = simulate_dvech(n=300, seed=4, d=3)
    result = oe.mgarch_dbekk(data, ["x", "y", "z"], intercept=True, tolerance=1e-7)
    assert result.extra["model"]["dimension"] == 3
    assert len(result.coefficients) == 3 + 6 + 6
    assert np.array(oe.forecast(result, 2).attrs["conditional_covariance"]).shape == (2, 3, 3)
    four = data.assign(w=data.x * 0.3 + data.y)
    for kind in ("dvech", "dbekk", "adcc"):
        with pytest.raises(AnalysisError, match="dimension"):
            getattr(oe, "mgarch_" + kind)(four, ["x", "y", "z", "w"])
    # Stationarity and positivity domains.
    with pytest.raises(KernelError, match="stationar"):
        kernels.validate_matrices({"mu": torch.zeros(2), "C": torch.eye(2, dtype=torch.float64),
                                   "a": torch.tensor([0.6, 0.2], dtype=torch.float64),
                                   "b": torch.tensor([0.8, 0.5], dtype=torch.float64)}, "dbekk")
    with pytest.raises(KernelError, match="stationar"):
        kernels.validate_matrices({"mu": torch.zeros(2),
                                   "C": torch.eye(2, dtype=torch.float64),
                                   "A": torch.tensor([[0.1, 0.5], [0.5, 0.1]],
                                                     dtype=torch.float64),
                                   "B": torch.tensor([[0.8, 0.6], [0.6, 0.8]],
                                                     dtype=torch.float64)}, "dvech")
    m = _adcc_matrices(np.r_[0.1, 0.1, 0.8, 0.1, 0.1, 0.8, 0.3, 0.6, 0.5], np.eye(2),
                       nbar=np.array([[0.5, 0.3], [0.3, 0.5]]))
    with pytest.raises(KernelError, match="delta"):
        kernels.validate_matrices(m, "adcc")


def test_persisted_state_tampering_is_refused(diagonal_fits, adcc_fit):
    _, fits = diagonal_fits
    broken = fits["dvech"].model_copy(deep=True)
    broken.extra["parameter_matrices"]["A"][0][0] *= 2
    with pytest.raises(AnalysisError, match="persisted"):
        oe.forecast(broken, 2)
    tampered = adcc_fit.model_copy(deep=True)
    tampered.extra["state"]["nbar"] = [[1.0, 0.0]]
    with pytest.raises(AnalysisError, match="invalid"):
        oe.forecast(tampered, 2)
