def critical_values(kind: str, trend: str, n: int, t: int, truncated: bool):
    """Bilinear interpolation on the tabulated N,T grid; never extrapolate."""
    if not (GRID[0] <= n <= GRID[-1] and GRID[0] <= t <= GRID[-1]):
        raise AnalysisError(
            "critical_values_unavailable",
            "Pesaran tables require 10 <= N,T <= 200; choose inference='none' for statistics without tabulated decisions.",
        )

    def bracket(value):
        upper = next(i for i, g in enumerate(GRID) if g >= value)
        lower = upper if GRID[upper] == value else upper - 1
        weight = 0.0 if lower == upper else (value - GRID[lower]) / (GRID[upper] - GRID[lower])
        return lower, upper, weight

    ni, nj, nw = bracket(n)
    ti, tj, tw = bracket(t)
    variant = "truncated" if truncated else "raw"
    answer = {}
    for level, variants in VALUES[kind][trend].items():
        rows = variants[variant]
        a = rows[ti][ni] * (1 - nw) + rows[ti][nj] * nw
        b = rows[tj][ni] * (1 - nw) + rows[tj][nj] * nw
        answer[level] = a * (1 - tw) + b * tw
    return answer
