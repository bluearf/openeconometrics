"""HEGY seasonal unit-root tests for quarterly and monthly series.

Hylleberg, Engle, Granger and Yoo (1990, J. Econometrics 44, 215-238) for
quarterly data and its monthly extension (Beaulieu and Miron 1993, J.
Econometrics 55, 305-328; the regressors here follow the general-S
construction of R's uroot ``hegy.regressors``). The auxiliary regression is

    Delta_S y_t = sum_{i=1..S} pi_i y_{i,t-1} + deterministic
                  + sum_{j=1..p} phi_j Delta_S y_{t-j} + e_t,   t = S+p+1..T,

with y_1 = (1 + L + ... + L^{S-1}) y (zero frequency), y_2 = -(1 - L + L^2 - ...
- L^{S-1}) y (frequency pi) and two filters per harmonic j = 1..S/2-1
(frequency 2 pi j/S); for S = 4 these are HEGY's -(1 - L^2) y_{t-2} and
-(1 - L^2) y_{t-1}.

Critical values are simulated (``hegy_tables.py``, generated by
``scripts/generate_unitroot_hegy_oracles.py``): neither the original HEGY
table (as transcribed in R's uroot) nor the Diaz-Emparanza (2014) response
surfaces ported in uroot replicated an independent simulation of these
statistics; see ``docs/econometrics/advanced-unitroot-fourier.md``.
"""

from __future__ import annotations

import math
from typing import Any

import torch
from torch import Tensor

from openecon.analysis_contracts import AnalysisError
from openecon.econometrics.core import table
from openecon.econometrics.unitroot import hegy_tables
from openecon.econometrics.unitroot.augmented import check_lag_option, choose_lags, nested_fits
from openecon.econometrics.unitroot.common import (
    CRITICAL_NAMES, check_choice, critical_columns,
)
from openecon.econometrics.unitroot.common import regress as ols
from openecon.econometrics.unitroot.series import one_series

CASES = ("none", "constant", "trend", "seasonal", "seasonal_trend")
LEVELS = ("1%", "2.5%", "5%", "10%")
SOURCE = ("OpenEconometrics seeded simulation, scripts/generate_unitroot_hegy_oracles.py "
          "(seasonal random walk null, iid N(0,1), no augmentation)")


def filters(seasons: int) -> Tensor:
    """[S, S] coefficients of x_{t-1-j} (j = 0..S-1) in the lagged HEGY regressors.

    Row 0 is y_1, row 1 is y_2 and rows 2j, 2j+1 the cosine/sine filters of
    harmonic j with the sign convention of uroot's ``hegy.regressors``.
    """
    lag = torch.arange(seasons, dtype=torch.float64)
    rows = [torch.ones(seasons, dtype=torch.float64), (-1.0) ** (lag + 1)]
    sign = -1.0
    for harmonic in range(1, seasons // 2):
        angle = (lag + 1) * (2.0 * math.pi * harmonic / seasons)
        rows.append(torch.cos(angle))
        rows.append(sign * torch.sin(angle))
        if harmonic == seasons // 4:
            sign = -sign
    return torch.stack(rows)


def _frequency_label(harmonic: int, seasons: int) -> str:
    numerator, denominator = 2 * harmonic, seasons
    divisor = math.gcd(numerator, denominator)
    numerator, denominator = numerator // divisor, denominator // divisor
    return ("" if numerator == 1 else str(numerator)) + "pi/" + str(denominator)


def _critical(seasons: int, case: str, statistic: str, nobs: int) -> dict[str, float]:
    """Simulated quantiles interpolated linearly in 1/N; the end rows outside the grid."""
    nodes = hegy_tables.NODES[seasons]
    rows = hegy_tables.CRITICAL[seasons][case][statistic]
    if nobs <= nodes[0]:
        row = rows[0]
    elif nobs >= nodes[-1]:
        row = rows[-1]
    else:
        index = next(i for i in range(1, len(nodes)) if nobs <= nodes[i])
        left, right = nodes[index - 1], nodes[index]
        weight = (1.0 / left - 1.0 / nobs) / (1.0 / left - 1.0 / right)
        row = tuple(a + weight * (b - a) for a, b in zip(rows[index - 1], rows[index],
                                                          strict=True))
    return dict(zip(LEVELS, row, strict=True))


def _deterministic(n: int, seasons: int, case: str) -> Tensor:
    columns = []
    if case != "none":
        columns.append(torch.ones(n, dtype=torch.float64))
    if case in ("trend", "seasonal_trend"):
        columns.append(torch.arange(1, n + 1, dtype=torch.float64) / n)
    if case in ("seasonal", "seasonal_trend"):
        position = torch.arange(n) % seasons
        columns.extend((position == season).to(torch.float64) for season in range(1, seasons))
    if not columns:
        return torch.empty((n, 0), dtype=torch.float64)
    return torch.stack(columns, dim=1)


def hegy(data: Any, y: str, *, time: str | None = None, seasons: int = 4,
         deterministic: str = "seasonal", lags: int | str = 0, maxlag: int | None = None):
    """HEGY test for seasonal and zero-frequency unit roots (quarterly or monthly).

    Model and estimator
    -------------------
    OLS of the auxiliary regression (module docstring) on t = S+p+1..T. The
    statistics, with classical OLS standard errors and F tests of exclusion
    restrictions (F = Wald / q with s^2 = SSR/(N - K)):

    - ``t_1``: t ratio of pi_1, H0 a unit root at frequency 0 (lower tail);
    - ``t_2``: t ratio of pi_2, H0 a unit root at frequency pi (lower tail);
    - ``F_a_b``: F test of each harmonic pair (pi_3, pi_4 for S = 4: the
      complex roots +-i at frequency pi/2; five pairs for S = 12), upper tail;
    - ``F_2_S``: all seasonal unit roots (pi_2 = ... = pi_S = 0), upper tail;
    - ``F_1_S``: all unit roots including frequency 0 (Ghysels, Lee and Noh
      1994), upper tail.

    Parameters
    ----------
    data, y, time : as in ``oe.dfuller``; the observations must be consecutive
        seasons (rows in order or a consecutive integer ``time``).
    seasons : 4 (quarterly, default) or 12 (monthly).
    deterministic : ``"none"``, ``"constant"``, ``"trend"`` (constant and
        trend), ``"seasonal"`` (constant and S - 1 seasonal dummies, default)
        or ``"seasonal_trend"``. Seasonal dummies are cyclic indicators from the
        first regression row; their phase does not affect any statistic.
    lags : number p of lagged Delta_S y terms (default 0), or ``"aic"``,
        ``"bic"`` or ``"t"`` to choose p over 0..maxlag on the common sample
        (the rules of ``oe.zandrews``), refitting the chosen p on its full
        sample (as uroot's ``hegy.test``).
    maxlag : largest p for automatic selection; default Schwert's rule capped
        by the sample.

    Critical values
    ---------------
    Seeded Monte Carlo quantiles (``hegy_tables``) at N = 40..1280 regression
    observations (quarterly) and 120..1200 (monthly), interpolated linearly in
    1/N at the regression's N = T - S - p; the end rows are used outside the
    grid, with a note. They are simulated without augmentation under iid
    errors; with lags they are asymptotic approximations. ``p_value`` is None.

    Returns
    -------
    A table indexed ``t_1``, ``t_2``, ``F_3_4`` (..., ``F_11_12``), ``F_2_S``,
    ``F_1_S`` with columns statistic, p_value, the three critical values,
    ``tail`` and ``frequency``. ``attrs``: ``statistics`` (dict),
    ``critical_values`` (dict of dicts, with 2.5%), ``reject``, ``seasons``,
    ``deterministic``, ``lags``, ``lag_method``, ``maxlag``, ``nobs``,
    ``df_resid``, ``nobs_series``, ``critical_value_source``, ``label``,
    ``notes``.

    R: ``uroot::hegy.test(ts(y, frequency = 4), deterministic = c(1, 0, 1),
    lag.method = "fixed", maxlag = 0)`` gives the same statistics.

    Example
    -------
    >>> result = oe.hegy(df, "sales", seasons=4, deterministic="seasonal", lags="bic")
    >>> result.loc["F_3_4", "statistic"], result.attrs["reject"]["t_1"]
    """
    if seasons not in (4, 12) or isinstance(seasons, bool):
        raise AnalysisError("invalid_option", "seasons must be 4 (quarterly) or 12 (monthly).")
    check_choice(deterministic, "deterministic", CASES)
    x, _ = one_series(data, y, time, "The HEGY test", minimum=4 * seasons)
    if deterministic != "none":
        x = x - x[0]                     # every statistic is invariant to the level here
    total = x.shape[0]
    n = total - seasons
    det_all = _deterministic(n, seasons, deterministic)
    fixed = det_all.shape[1] + seasons
    method, order = check_lag_option(lags, maxlag, n + 1, fixed, "the HEGY regression")
    # Row r (0-based) is observation t = S + r: regressors from x_{t-1}, ..., x_{t-S}.
    lagged = torch.stack([x[seasons - 1 - j:total - 1 - j] for j in range(seasons)], dim=1)
    regressors = lagged @ filters(seasons).T                       # [n, S]
    target = x[seasons:] - x[:-seasons]                            # Delta_S y_t

    def design(first: int, p: int) -> Tensor:
        """Rows first..n-1: [deterministic, HEGY regressors, p lags, target]."""
        columns = [det_all[first:], regressors[first:]]
        if p:
            columns.append(torch.stack([target[first - j:n - j] for j in range(1, p + 1)], dim=1))
        columns.append(target[first:, None])
        return torch.cat(columns, dim=1)

    if method != "fixed":
        full = design(order, order)
        fits = nested_fits(n - order, fixed, order, lambda low, high: full[low:high],
                           "The HEGY regression")
        p = choose_lags(fits, method)
    else:
        p = order
    if n - p <= fixed + p:
        raise AnalysisError("insufficient_observations", f"The HEGY regression has "
                            f"{max(n - p, 0)} observation(s) for {fixed + p} parameter(s); use "
                            "fewer lags or a longer series.")
    rows = design(p, p)
    fit = ols(rows[:, :-1].contiguous(), rows[:, -1].contiguous(), "The HEGY regression")
    if fit.exact or not fit.s2 > 0.0:
        raise AnalysisError("perfect_fit", "The HEGY regression fits the series exactly; the "
                            "series is deterministic and the tests are undefined.")
    start = det_all.shape[1]
    beta, covariance = fit.beta, fit.s2 * fit.xtx_inv

    def wald(columns: list[int]) -> float:
        index = torch.tensor([start + c for c in columns])
        b = beta[index]
        v = covariance[index][:, index]
        return float(b @ torch.linalg.solve(v, b)) / len(columns)

    statistics = {"t_1": float(beta[start] / fit.se[start]),
                  "t_2": float(beta[start + 1] / fit.se[start + 1])}
    labels = {"t_1": ("lower", "0"), "t_2": ("lower", "pi")}
    for harmonic in range(1, seasons // 2):
        name = f"F_{2 * harmonic + 1}_{2 * harmonic + 2}"
        statistics[name] = wald([2 * harmonic, 2 * harmonic + 1])
        labels[name] = ("upper", "+-" + _frequency_label(harmonic, seasons))
    seasonal_name, all_name = f"F_2_{seasons}", f"F_1_{seasons}"
    statistics[seasonal_name] = wald(list(range(1, seasons)))
    statistics[all_name] = wald(list(range(seasons)))
    labels[seasonal_name] = ("upper", "all seasonal")
    labels[all_name] = ("upper", "all")
    table_names = {"t_1": "t_1", "t_2": "t_2", seasonal_name: "F_seasonal", all_name: "F_all"}
    values, reject, rows_out = {}, {}, []
    for name, statistic in statistics.items():
        if not math.isfinite(statistic):
            raise AnalysisError("numerical_failure", "A HEGY statistic is numerically "
                                "unresolved; rescale the series.")
        key = table_names.get(name, "pair")
        values[name] = _critical(seasons, deterministic, key, fit.nobs)
        tail = labels[name][0]
        reject[name] = {level: (statistic < cv if tail == "lower" else statistic > cv)
                        for level, cv in values[name].items()}
        rows_out.append([statistic, None, *critical_columns(values[name]), tail, labels[name][1]])
    nodes = hegy_tables.NODES[seasons]
    notes = [f"Critical values: {SOURCE}; interpolated linearly in 1/N at N = {fit.nobs}. "
             "p-values are not reported.",
             "t_1, t_2 reject for small values; the F statistics reject for large values."]
    if fit.nobs < nodes[0]:
        notes.append(f"N = {fit.nobs} is below the smallest simulated sample ({nodes[0]:g}); "
                     "that row is used.")
    elif fit.nobs > nodes[-1]:
        notes.append(f"N = {fit.nobs} exceeds the largest simulated sample ({nodes[-1]:g}); "
                     "that row (close to the asymptotic distribution) is used.")
    if p:
        notes.append("With augmentation the simulated (p = 0) critical values are asymptotic "
                     "approximations.")
    attrs = {
        "title": f"HEGY seasonal unit-root test for {y}", "test": "hegy", "series": y,
        "statistics": statistics, "statistic": statistics["t_1"], "p_value": None,
        "p_value_reason": "Critical values are simulated quantiles; no p-value is reported.",
        "inference_status": "critical_values_only", "critical_values": values,
        "reject": reject, "seasons": seasons, "deterministic": deterministic, "lags": p,
        "lag_method": method, "maxlag": order if method != "fixed" else None,
        "nobs": fit.nobs, "df_resid": fit.df, "nobs_series": total,
        "critical_value_source": SOURCE, "null": "Unit roots at the tested frequencies",
        "alternative": "Stationarity at the tested frequencies",
        "label": "HEGY t and F statistics (H0: seasonal/zero-frequency unit roots)",
        "notes": notes,
    }
    return table(rows_out, columns=["statistic", "p_value", *CRITICAL_NAMES, "tail", "frequency"],
                 index=list(statistics), **attrs)
